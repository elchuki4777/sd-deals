create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  appointment_number bigint generated by default as identity unique,
  customer_id uuid not null references auth.users(id) on delete cascade,
  service text not null check (service in ('Full PC Assembly','Custom Gaming PC Build','PC Upgrade','PC Repair','PC Diagnostics','Cable Management','PC Consultation')),
  requested_date date not null,
  requested_time text not null,
  suggested_date date,
  suggested_time text,
  status text not null default 'Pending Approval' check (status in ('Pending Approval','Confirmed','Waiting for Parts','Parts Received','Parts Ordered','Building PC','Cable Management','Testing','Benchmarking','Ready for Pickup','Completed','Cancelled')),
  parts_method text not null,
  parts_owned text[] not null default '{}',
  parts_needed text[] not null default '{}',
  part_details jsonb not null default '{}',
  budget text,
  pc_preferences jsonb not null default '{}',
  delivery_method text not null,
  customer_name text not null,
  phone text not null,
  email text not null,
  preferred_contact text not null check (preferred_contact in ('Text Message','Phone Call','Email')),
  customer_notes text not null default '',
  image_paths text[] not null default '{}',
  admin_notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.availability_settings (
  id integer primary key default 1 check (id=1),
  available_days text[] not null default array['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday'],
  available_hours text[] not null default array['10:00 AM','11:00 AM','12:00 PM','1:00 PM','2:00 PM','3:00 PM','4:00 PM','5:00 PM','6:00 PM'],
  appointment_duration text not null default '1 hour' check (appointment_duration in ('30 minutes','1 hour','2 hours')),
  maximum_appointments_per_day integer not null default 5 check (maximum_appointments_per_day>0),
  blocked_dates date[] not null default '{}',
  unavailable_hours jsonb not null default '{}',
  updated_at timestamptz not null default now()
);
insert into public.availability_settings(id) values (1) on conflict(id) do nothing;
-- Expose only public availability fields. Keep shipping details in the admin-only table below.
create or replace view public.public_availability_settings with (security_invoker=true) as
  select id,available_days,available_hours,appointment_duration,maximum_appointments_per_day,blocked_dates,unavailable_hours
  from public.availability_settings;
grant select on public.public_availability_settings to anon,authenticated;
