create table if not exists public.build_events (
  id uuid primary key default gen_random_uuid(),
  appointment_id uuid not null references public.appointments(id) on delete cascade,
  customer_id uuid not null references auth.users(id) on delete cascade,
  milestone text not null check (milestone in ('Appointment Confirmed','Parts Received / Ordered','PC Assembly Started','Cable Management','Windows / Drivers','Testing','Benchmarking','Ready for Pickup','Completed')),
  completed boolean not null default false,
