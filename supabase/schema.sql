create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$ begin new.updated_at=now(); return new; end; $$;
create or replace function public.seed_build_timeline()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
 insert into public.build_events(appointment_id,customer_id,milestone,completed,occurred_at)
 values(new.id,new.customer_id,'Appointment Confirmed',false,null) on conflict(appointment_id,milestone) do nothing;
 return new;
end; $$;
create or replace function public.sync_build_timeline()
returns trigger language plpgsql security definer set search_path = '' as $$
declare milestone_name text;
begin
 if new.status='Confirmed' and old.status is distinct from new.status then
  update public.build_events set completed=true,occurred_at=now() where appointment_id=new.id and milestone='Appointment Confirmed';
 end if;
 milestone_name:=case
  when new.status in ('Waiting for Parts','Parts Received','Parts Ordered') then 'Parts Received / Ordered'
  when new.status='Building PC' then 'PC Assembly Started'
  when new.status='Cable Management' then 'Cable Management'
  when new.status='Testing' then 'Testing'
  when new.status='Benchmarking' then 'Benchmarking'
  when new.status='Ready for Pickup' then 'Ready for Pickup'
  when new.status='Completed' then 'Completed' else null end;
 if milestone_name is not null then update public.build_events set completed=true,occurred_at=coalesce(occurred_at,now()) where appointment_id=new.id and milestone=milestone_name; end if;
 return new;
end; $$;
